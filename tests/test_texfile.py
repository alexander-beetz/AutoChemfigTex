from __future__ import annotations

import unittest

from mol2chemfig_helper.texfile import (
    Entry,
    TexFileError,
    append_block,
    duplicate_identifiers,
    find_conflict,
    identifier_records,
    parse_managed_blocks,
    render_block,
    replace_managed_block,
    overwrite_text,
)


def entry(name: str = "Azid", **kwargs: object) -> Entry:
    values = {
        "name": name,
        "identifier": "O=C1N=N1",
        "input_format": "direct",
        "label": name,
        "chemfig": r"\chemfig{-[:30]N=[:30]N}",
        "m2c_args": ("-f", "-w"),
    }
    values.update(kwargs)
    return Entry(**values)  # type: ignore[arg-type]


class RenderBlockTests(unittest.TestCase):
    def test_renders_named_structure_with_conventional_label(self) -> None:
        block = render_block(entry())
        self.assertEqual(
            block,
            "\n".join(
                [
                    "% === mol2chemfig-helper:Azid:BEGIN ===",
                    "% Generated by mol2chemfig-helper; do not edit this block manually.",
                    "% identifier: direct O=C1N=N1",
                    "% mol2chemfig options: -f -w -i direct",
                    "\\newcommand{\\AzidName}{%",
                    "  \\textbf{\\cmpd{Azid}}%",
                    "}",
                    "",
                    "\\DeclareRobustCommand{\\AzidStructure}{%",
                    "  \\chemfig{-[:30]N=[:30]N}%",
                    "}",
                    "",
                    "\\DeclareRobustCommand{\\Azid}{%",
                    "  \\chemname{\\AzidStructure}{\\AzidName}%",
                    "}",
                    "",
                    "\\DeclareRobustCommand{\\AzidExtras}{%",
                    "  \\Azid%",
                    "}",
                    "% === mol2chemfig-helper:Azid:END ===",
                ]
            ),
        )

    def test_name_macro_contains_only_the_number(self) -> None:
        block = render_block(entry(formula="C6H6", mw="78.11"))
        self.assertIn(
            "\\newcommand{\\AzidName}{%\n  \\textbf{\\cmpd{Azid}}%\n}",
            block,
        )
        self.assertNotIn("shortstack", block.split("\\AzidStructure")[0])

    def test_renders_formula_and_molecular_weight_in_extras(self) -> None:
        block = render_block(entry(formula="C6H6", mw="78.11"))
        self.assertIn(
            "\\DeclareRobustCommand{\\AzidExtras}{%\n"
            "  \\chemname{\\AzidStructure}{%\n"
            "    \\shortstack[c]{%\n"
            "      \\AzidName\\\\\n"
            "      C6H6\\\\\n"
            "      78.11%\n"
            "    }\n"
            "  }%\n"
            "}",
            block,
        )
        self.assertIn("% sum formula: C6H6", block)
        self.assertIn("% molecular weight: 78.11", block)

    def test_renders_formula_only(self) -> None:
        block = render_block(entry(formula="C6H6"))
        self.assertIn("      C6H6%\n", block)
        self.assertNotIn("78.11", block)

    def test_renders_molecular_weight_only(self) -> None:
        block = render_block(entry(mw="78.11"))
        self.assertIn("      78.11%\n", block)
        self.assertNotIn("sum formula", block)

    def test_extras_alias_without_formula_or_weight(self) -> None:
        block = render_block(entry())
        self.assertIn(
            "\\DeclareRobustCommand{\\AzidExtras}{%\n  \\Azid%\n}",
            block,
        )

    def test_renders_custom_compound_key(self) -> None:
        block = render_block(entry(label="azid-1"))
        self.assertIn("\\textbf{\\cmpd{azid-1}}", block)

    def test_renders_multiline_chemfig_with_indent(self) -> None:
        block = render_block(entry(chemfig="\\chemfig{\n  -N\n}"))
        self.assertIn("  \\chemfig{\n    -N\n  }%", block)

    def test_empty_chemfig_raises(self) -> None:
        with self.assertRaises(TexFileError):
            render_block(entry(chemfig=""))


class ManagedBlockTests(unittest.TestCase):
    def test_parse_and_replace_managed_block(self) -> None:
        first = render_block(entry())
        text = "preamble\n\n" + first + "\n\n% hand-written tail\n"
        blocks = parse_managed_blocks(text)
        self.assertIn("Azid", blocks)
        self.assertEqual(blocks["Azid"].text, first)

        second = render_block(entry(identifier="CCO"))
        replaced = replace_managed_block(text, blocks["Azid"], second)
        self.assertIn("% identifier: direct CCO", replaced)
        self.assertNotIn("O=C1N=N1", replaced)
        self.assertTrue(replaced.endswith("% hand-written tail\n"))

    def test_duplicate_managed_block_raises(self) -> None:
        block = render_block(entry())
        with self.assertRaises(TexFileError):
            parse_managed_blocks(block + "\n" + block + "\n")

    def test_unterminated_block_raises(self) -> None:
        with self.assertRaises(TexFileError):
            parse_managed_blocks("% === mol2chemfig-helper:Azid:BEGIN ===\n")

    def test_end_without_begin_raises(self) -> None:
        with self.assertRaises(TexFileError):
            parse_managed_blocks("% === mol2chemfig-helper:Azid:END ===\n")

    def test_mismatched_end_raises(self) -> None:
        text = (
            "% === mol2chemfig-helper:Azid:BEGIN ===\n"
            "% === mol2chemfig-helper:Other:END ===\n"
        )
        with self.assertRaises(TexFileError):
            parse_managed_blocks(text)

    def test_nested_begin_raises(self) -> None:
        text = (
            "% === mol2chemfig-helper:Azid:BEGIN ===\n"
            "% === mol2chemfig-helper:Other:BEGIN ===\n"
        )
        with self.assertRaises(TexFileError):
            parse_managed_blocks(text)


class ConflictTests(unittest.TestCase):
    def test_no_conflict_on_empty_file(self) -> None:
        conflict = find_conflict("", entry(), {})
        self.assertFalse(conflict.exists)

    def test_managed_block_conflict_can_be_overwritten(self) -> None:
        text = render_block(entry()) + "\n"
        blocks = parse_managed_blocks(text)
        conflict = find_conflict(text, entry(), blocks)
        self.assertTrue(conflict.exists)
        self.assertTrue(conflict.can_overwrite)
        self.assertIsNotNone(overwrite_text(text, conflict, entry(identifier="CCO")))

    def test_manual_definition_conflict_can_be_overwritten(self) -> None:
        text = "before\n\\DeclareRobustCommand{\\Azid}{\\chemfig{-N=N}}\nafter\n"
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertTrue(conflict.can_overwrite)
        replaced = overwrite_text(text, conflict, entry())
        self.assertIsNotNone(replaced)
        assert replaced is not None
        self.assertIn("% === mol2chemfig-helper:Azid:BEGIN ===", replaced)
        self.assertNotIn("\\DeclareRobustCommand{\\Azid}{\\chemfig", replaced)
        self.assertTrue(replaced.startswith("before\n"))

    def test_manual_definition_sharing_line_is_not_overwritable(self) -> None:
        text = "before \\newcommand{\\Azid}{x} after\n"
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)
        self.assertIsNone(overwrite_text(text, conflict, entry()))

    def test_label_macro_conflict_blocks_overwrite(self) -> None:
        text = "\\newcommand{\\AzidName}{manual}\n"
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)
        self.assertIsNone(overwrite_text(text, conflict, entry()))

    def test_raw_macro_conflict_blocks_overwrite(self) -> None:
        text = "\\newcommand{\\AzidStructure}{manual}\n"
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)

    def test_extras_macro_conflict_blocks_overwrite(self) -> None:
        text = "\\newcommand{\\AzidExtras}{manual}\n"
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)
        self.assertIsNone(overwrite_text(text, conflict, entry()))

    def test_new_name_cannot_collide_with_another_blocks_label_macro(self) -> None:
        text = render_block(entry(name="Ethanol")) + "\n"
        blocks = parse_managed_blocks(text)
        conflict = find_conflict(text, entry(name="EthanolName"), blocks)
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)
        self.assertEqual(conflict.blocked_by, ("Ethanol",))
        self.assertIsNone(overwrite_text(text, conflict, entry(name="EthanolName")))

    def test_new_name_cannot_collide_with_another_blocks_raw_macro(self) -> None:
        text = render_block(entry(name="Ethanol")) + "\n"
        blocks = parse_managed_blocks(text)
        conflict = find_conflict(text, entry(name="EthanolStructure"), blocks)
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)
        self.assertEqual(conflict.blocked_by, ("Ethanol",))

    def test_new_name_cannot_collide_with_another_blocks_extras_macro(self) -> None:
        text = render_block(entry(name="Ethanol")) + "\n"
        blocks = parse_managed_blocks(text)
        conflict = find_conflict(text, entry(name="EthanolExtras"), blocks)
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)
        self.assertEqual(conflict.blocked_by, ("Ethanol",))

    def test_two_manual_definitions_are_ambiguous(self) -> None:
        text = (
            "\\newcommand{\\Azid}{one}\n"
            "\\renewcommand{\\Azid}{two}\n"
        )
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)

    def test_let_definition_is_not_overwritable(self) -> None:
        text = "\\let\\Azid\\relax\n"
        conflict = find_conflict(text, entry(), {})
        self.assertTrue(conflict.exists)
        self.assertFalse(conflict.can_overwrite)


class IdentifierTests(unittest.TestCase):
    def test_records_and_duplicate_detection(self) -> None:
        text = (
            render_block(entry(name="One", identifier="CCO"))
            + "\n\n"
            + render_block(entry(name="Two", identifier="CCO"))
            + "\n"
        )
        records = identifier_records(text, parse_managed_blocks(text))
        self.assertEqual([record.name for record in records], ["One", "Two"])
        duplicates = duplicate_identifiers(records, entry(name="Two", identifier="CCO"))
        self.assertEqual([record.name for record in duplicates], ["One"])

    def test_identifier_with_percent_sign_is_preserved(self) -> None:
        text = render_block(entry(identifier="C1CC%2CCC1")) + "\n"
        records = identifier_records(text, parse_managed_blocks(text))
        self.assertEqual(records[0].identifier, "C1CC%2CCC1")


class AppendTests(unittest.TestCase):
    def test_append_to_empty_file(self) -> None:
        block = render_block(entry())
        self.assertEqual(append_block("", block), block + "\n")

    def test_append_adds_one_blank_line(self) -> None:
        block = render_block(entry())
        self.assertEqual(append_block("preamble", block), "preamble\n\n" + block + "\n")
        self.assertEqual(
            append_block("preamble\n\n", block), "preamble\n\n" + block + "\n"
        )

    def test_append_leaves_no_extra_blank_line(self) -> None:
        block = render_block(entry())
        result = append_block("preamble\n", block)
        self.assertTrue(result.endswith(block + "\n"))
        self.assertNotIn(block + "\n\n", result)


if __name__ == "__main__":
    unittest.main()
